"""develop_repair_hybrid: the declared EXPLORATORY emergence measurement (directive 2026-10-21, section 7).

The declaration (``docs/evidence/greg-repair-hybrid/2026-10-21-exploratory/DECLARATION.md``) and this script were
committed together BEFORE any instance of the review seeds below was generated by ``repair_instance``. The criteria
in ``CRITERIA`` are evaluated mechanically by ``summarise``; nothing here is tuned after the review run.

    D=docs/evidence/greg-repair-hybrid/2026-10-21-exploratory
    PYTHONPATH=. taskset -c 2,3 python scripts/repair_hybrid_explore.py dev --out $D/dev.json
    PYTHONPATH=. taskset -c 2,3 python scripts/repair_hybrid_explore.py review --out $D/review.json

EXPLORATORY: not admission, not a P8 cycle, not evidence of general superiority. Read-only; creates no authority.
"""
from __future__ import annotations

import argparse
from concurrent.futures import ProcessPoolExecutor
import json
import math
from pathlib import Path
import statistics
import sys
import time

ROOT = Path(__file__).resolve().parents[1]
if str(ROOT) not in sys.path:
    sys.path.insert(0, str(ROOT))

from greg.cognition import evolution as E                         # noqa: E402
from greg.cognition.genomes import developmental as D             # noqa: E402
from greg.cognition.genomes import developmental_hybrid as HY     # noqa: E402

DEV_SEEDS = tuple(range(0, 10))
REVIEW_SEEDS = tuple(range(4000, 4640))       # 640 items; unused by repair_instance in both lineages (ledger, 10e438d3)
TOL = 1e-9
WORKERS = 2
ARMS = ("hybrid", "local_only", "central_only", "naive_switch", "vouch_only")
SUBREGIONS = ("reliable_controller", "crashed_controller", "stale_controller")
# The declared criteria (DECLARATION.md section 3). E1-E4 and A1-A2 decide the verdict; E5 is reported only.
CRITERIA = {
    "E1": "reliable: hybrid loses to central_only on at most 1% of items, and makes 0 false claims there",
    "E2a": "stale: hybrid mean quality > central_only's, hybrid makes 0 false claims and central_only > 0",
    "E2b": "stale: hybrid wins more paired items than it loses against central_only",
    "E3": "all items: hybrid makes 0 false claims and fewer than central_only",
    "E4": "reliable: hybrid actions <= central_only's on every item and < local_only's on every item",
    "A1": "ablation: naive_switch makes > 0 false claims on stale items (the vouching is what removes them)",
    "A2": "ablation: vouch_only makes 0 false claims and its stale mean quality is below the hybrid's (the "
          "fallback is what restores function)",
    "E5": "reported only: hybrid beats local_only on paired items overall and central_only on mean quality overall",
}


def guard(seeds) -> tuple:
    seeds = tuple(seeds)
    if not (set(seeds) <= set(DEV_SEEDS) or set(seeds) <= set(REVIEW_SEEDS)):
        raise ValueError("only development seeds 0-9 or the declared review seeds 4000-4639")
    return seeds


def _arm_outputs(data):
    return {"hybrid": HY.hybrid_solve(data, {}), "local_only": HY.hybrid_local_only(data),
            "central_only": D.repair_central_replanner(data), "naive_switch": HY.hybrid_naive_switch(data),
            "vouch_only": HY.hybrid_vouch_only(data)}


def run_item(seed: int) -> dict:
    data, truth = D.repair_instance(seed)
    outs = _arm_outputs(data)
    hyb = outs["hybrid"]
    row = {"seed": seed, "subregion": HY.hybrid_subregion(data),
           "hybrid_verified": all(HY.hybrid_verify(data, hyb["output"], hyb["certificate"]).values())
           if hyb["output"] is not None else None,
           "hybrid_owner": hyb["certificate"].get("owner"),
           "hybrid_first_discrepancy": hyb["certificate"].get("first_discrepancy_step"), "arms": {}}
    for arm in ARMS:
        out = hyb["output"] if arm == "hybrid" else outs[arm]
        score = D.repair_score(data, truth, out)
        row["arms"][arm] = {"quality": score["quality"], "category": score["category"],
                            "actions": out["actions"] if isinstance(out, dict) else None,
                            "claims": len(out["claimed"]) if isinstance(out, dict) else 0}
    return row


def paired(rows, a, b):
    wins = sum(1 for r in rows if r["arms"][a]["quality"] > r["arms"][b]["quality"] + TOL)
    losses = sum(1 for r in rows if r["arms"][b]["quality"] > r["arms"][a]["quality"] + TOL)
    return {"wins": wins, "ties": len(rows) - wins - losses, "losses": losses,
            "sign_p_one_sided": E.sign_test(wins, losses)}


def wrong(rows, arm):
    from scipy.stats import beta
    n, w = len(rows), sum(1 for r in rows if r["arms"][arm]["category"] == "wrong")
    return {"wrong": w, "n": n, "upper_95": 1.0 if w >= n else round(float(beta.ppf(0.95, w + 1, n - w)), 6)}


def block(rows):
    out = {"n": len(rows)}
    for arm in ARMS:
        q = [r["arms"][arm]["quality"] for r in rows]
        acts = [r["arms"][arm]["actions"] for r in rows if r["arms"][arm]["actions"] is not None]
        out[arm] = {"mean_quality": statistics.fmean(q) if q else None,
                    "mean_quality_without_wrong": statistics.fmean(
                        [r["arms"][arm]["quality"] for r in rows if r["arms"][arm]["category"] != "wrong"] or [0.0]),
                    "p8_mean_loss": math.inf if any(r["arms"][arm]["category"] == "wrong" for r in rows)
                    else (-statistics.fmean(q) if q else None),
                    "median_actions": statistics.median(acts) if acts else None, "errors": wrong(rows, arm)}
    out["paired"] = {f"hybrid_vs_{b}": paired(rows, "hybrid", b) for b in ARMS if b != "hybrid"}
    out["paired"]["naive_switch_vs_central_only"] = paired(rows, "naive_switch", "central_only")
    return out


def summarise(rows) -> dict:
    by = {s: [r for r in rows if r["subregion"] == s] for s in SUBREGIONS}
    rel, stale = by["reliable_controller"], by["stale_controller"]
    allb, relb, staleb = block(rows), block(rel), block(stale)
    checks = {
        "E1": (relb["paired"]["hybrid_vs_central_only"]["losses"] <= math.floor(0.01 * len(rel))
               and relb["hybrid"]["errors"]["wrong"] == 0),
        "E2a": (staleb["hybrid"]["mean_quality"] > staleb["central_only"]["mean_quality"]
                and staleb["hybrid"]["errors"]["wrong"] == 0 and staleb["central_only"]["errors"]["wrong"] > 0),
        "E2b": staleb["paired"]["hybrid_vs_central_only"]["wins"] > staleb["paired"]["hybrid_vs_central_only"]["losses"],
        "E3": (allb["hybrid"]["errors"]["wrong"] == 0
               and allb["hybrid"]["errors"]["wrong"] < allb["central_only"]["errors"]["wrong"]),
        "E4": all(r["arms"]["hybrid"]["actions"] <= r["arms"]["central_only"]["actions"]
                  and r["arms"]["hybrid"]["actions"] < r["arms"]["local_only"]["actions"] for r in rel),
        "A1": staleb["naive_switch"]["errors"]["wrong"] > 0,
        "A2": (allb["vouch_only"]["errors"]["wrong"] == 0
               and staleb["vouch_only"]["mean_quality"] < staleb["hybrid"]["mean_quality"]),
        "E5": (allb["paired"]["hybrid_vs_local_only"]["wins"] > allb["paired"]["hybrid_vs_local_only"]["losses"]
               and allb["hybrid"]["mean_quality"] > allb["central_only"]["mean_quality"]),
    }
    deciding = ("E1", "E2a", "E2b", "E3", "E4", "A1", "A2")
    if all(checks[c] for c in deciding):
        verdict = "EMERGENCE_SUPPORTED"
    elif all(checks[c] for c in deciding if c != "E2b"):
        verdict = "PARTIAL: every declared criterion but E2b (paired wins on stale items)"
    else:
        verdict = "NOT_SUPPORTED"
    return {"label": "EXPLORATORY (not admission, not a P8 cycle)", "criteria": CRITERIA, "checks": checks,
            "verdict": verdict, "all": allb, "by_subregion": {s: block(v) for s, v in by.items()},
            "hybrid_unverified_items": [r["seed"] for r in rows if r["hybrid_verified"] is False],
            "hybrid_owner_counts": {o: sum(1 for r in rows if r["hybrid_owner"] == o) for o in ("planner", "local")},
            "hybrid_discrepancy_by_subregion": {s: sum(1 for r in v if r["hybrid_first_discrepancy"] is not None)
                                                for s, v in by.items()}}


def main(argv=None) -> int:
    ap = argparse.ArgumentParser(description=__doc__.split("\n")[0])
    ap.add_argument("mode", choices=("dev", "review"))
    ap.add_argument("--out", type=Path, required=True)
    args = ap.parse_args(argv)
    if args.out.exists():
        raise SystemExit(f"{args.out} exists: outputs are never overwritten")
    seeds = guard(DEV_SEEDS if args.mode == "dev" else REVIEW_SEEDS)
    start = time.time()
    with ProcessPoolExecutor(WORKERS) as pool:
        rows = list(pool.map(run_item, seeds, chunksize=8))
    result = {"schema": "greg-repair-hybrid-exploratory/1", "mode": args.mode, "seeds": [seeds[0], seeds[-1]],
              "hybrid_version": HY.VERSION, "wall_clock_s": round(time.time() - start, 1),
              "summary": summarise(rows), "items": rows}
    args.out.parent.mkdir(parents=True, exist_ok=True)
    args.out.write_text(json.dumps(result, indent=1, sort_keys=True, default=str) + "\n")
    print(json.dumps({"verdict": result["summary"]["verdict"], "checks": result["summary"]["checks"]}, indent=1))
    return 0


if __name__ == "__main__":
    sys.exit(main())
