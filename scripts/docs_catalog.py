#!/usr/bin/env python3
"""One catalog of every document and record in the repository, without moving any.

Read-only over the tree; it writes only the catalog file you name. Files stay
where they are, because code, tests, frozen evaluations, receipts and open
branches refer to them by path (see ``docs/CATALOG.md``'s header for the counts).
The catalog is the organization: every file appears exactly once, under its
area, its kind and its date.

Usage::

    python scripts/docs_catalog.py --write docs/CATALOG.md   # regenerate
    python scripts/docs_catalog.py --check docs/CATALOG.md   # exit 1 if stale

``--check`` reports staleness. It is deliberately not a per-PR gate: a generated
file that every PR must regenerate conflicts between parallel PRs (pain points
P-1 and P-3). The weekly review reports drift, and the integrator regenerates the
catalog at intake.
"""
from __future__ import annotations

import argparse
import json
import re
import subprocess
import sys
from collections import defaultdict
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
CATALOG = "docs/CATALOG.md"

AREAS = {
    "(top)": "Doctrine, orders and top-level references",
    "intent": "Founder intent records and their verbatim sources",
    "collaboration": "Collaboration records: handoffs, deliberations, reviews, reconciliations",
    "decisions": "Architecture decision records",
    "deliberations": "Founder rulings",
    "evidence": "Measured evidence (frozen runs, admissions, proofs)",
    "cortex": "Cortex and Seed Genome specifications and evidence",
    "opus-maximus": "OPUS MAXIMUS deliverables A–L",
    "open-source": "Open-source mechanism harvest records",
    "release": "Release records",
    "mechanisms": "Mechanism Cards",
    "developmental": "Developmental mechanism research",
}

# Kind of a record, from its file name. First match wins; order matters.
KINDS = [
    ("Deliberation (five lenses, two passes)", r"deliberation|DELIBERATION"),
    ("Founder decisions and rulings", r"FOUNDER-(DECISIONS|ACTIONS|RULING)|ruling"),
    ("Intent record", r"^INTENT-|intents?-|FOUNDER-INTENT|intent-records"),
    ("Verbatim founder source", r"-source\.(md|txt)$|sources/"),
    ("Handoff", r"HANDOFF|handoff"),
    ("Reconciliation and convergence", r"RECONCIL|CONVERGENCE|convergence|METABOLISM|INHERITANCE"),
    ("Review and audit", r"REVIEW|review|AUDIT|audit|critique|VALIDATION|verification"),
    ("Requirements and coverage", r"requirement|REQUIREMENT|COVERAGE|coverage|checkpoint"),
    ("Inventory, map and register", r"INVENTORY|inventory|MAP|map|REGISTER|census|CENSUS|INDEX|PAIN-POINTS"),
    ("Plan and procedure", r"PLAN|plan|SOP|START_HERE|ORDER|PROTOCOL|RUNBOOK|runbook|CADENCE"),
    ("Decision record", r"ADR|DECISION|decision"),
    ("Evidence and proof", r"evidence|EVIDENCE|PROOF|proof|receipt|trace"),
]
DATE = re.compile(r"(20\d\d)-?(\d\d)-?(\d\d)")


def _files(root: Path) -> list[str]:
    out = subprocess.run(["git", "ls-files"], cwd=root, check=True,
                         capture_output=True, text=True).stdout.split("\n")
    return [f for f in out if f]


def title_of(path: Path) -> str:
    """The document's own title: first Markdown heading, or a JSON id/title field."""
    try:
        if path.suffix == ".md":
            for line in path.read_text(errors="ignore").splitlines()[:40]:
                if line.startswith("#"):
                    return line.lstrip("#").strip()
        elif path.suffix == ".json" and path.stat().st_size < 2_000_000:
            data = json.loads(path.read_text(errors="ignore"))
            if isinstance(data, dict):
                for key in ("title", "intent_id", "name", "id", "decision_id", "kind"):
                    if isinstance(data.get(key), str):
                        return data[key]
    except (OSError, ValueError):
        pass
    return ""


def kind_of(name: str) -> str:
    for kind, pat in KINDS:
        if re.search(pat, name):
            return kind
    return "Other"


def date_of(name: str) -> str:
    m = DATE.search(name)
    return f"{m[1]}-{m[2]}-{m[3]}" if m else ""


def _cell(text: str) -> str:
    return text.replace("|", "\\|").replace("\n", " ")[:120]


def build(root: Path = ROOT) -> str:
    files = _files(root)
    docs = [f for f in files if f.startswith("docs/") and f != CATALOG]
    by_area: dict[str, list[str]] = defaultdict(list)
    for f in docs:
        parts = f.split("/")
        by_area[parts[1] if len(parts) > 2 else "(top)"].append(f)
    elsewhere = sorted(f for f in files if f.endswith(".md") and not f.startswith("docs/"))

    lines = [
        "# Catalog of documents and records",
        "",
        "Every file under `docs/` appears here exactly once, grouped by area and kind, newest first.",
        "Markdown files elsewhere in the tree are listed at the end. Generated by",
        "`scripts/docs_catalog.py`; regenerate it with `--write`, never by hand. "
        "The weekly repository review reports when it is stale.",
        "",
        "**Why nothing was moved:** most of these paths are named by code, tests, frozen",
        "evaluations, receipts or open branches. Moving them would break those readers or",
        "conflict with work in flight, so this catalog organizes them in place.",
        "For the state of every branch, see the newest `collaboration/BRANCH-CATALOG-*.md`.",
        "",
        "## Areas",
        "",
        "| Area | Files | What it holds |",
        "|---|---:|---|",
    ]
    order = [a for a in AREAS if a in by_area] + sorted(a for a in by_area if a not in AREAS)
    for a in order:
        anchor = re.sub(r"[^a-z0-9 -]", "", (AREAS.get(a, a)).lower()).replace(" ", "-")
        lines.append(f"| [`{a}`](#{anchor}) | {len(by_area[a])} | {AREAS.get(a, '')} |")
    lines.append(f"| Elsewhere (`*.md`) | {len(elsewhere)} | READMEs and notes beside code |")
    lines.append("")

    for a in order:
        lines += [f"## {AREAS.get(a, a)}", ""]
        rel = lambda f: f[len("docs/"):]  # noqa: E731 - links are relative to docs/
        if a == "evidence":
            # Evidence is grouped by its run directory; each directory is one result.
            dirs: dict[str, list[str]] = defaultdict(list)
            for f in by_area[a]:
                parts = f.split("/")
                dirs["/".join(parts[:4]) if len(parts) > 4 else f].append(f)
            lines += ["| Run or record | Files | Date | Title |", "|---|---:|---|---|"]
            for d in sorted(dirs, key=lambda d: (date_of(d), d), reverse=True):
                fs = dirs[d]
                readme = next((f for f in fs if f.endswith("README.md")), fs[0])
                lines.append(f"| [`{rel(d)}`]({rel(readme)}) | {len(fs)} | {date_of(d)} | "
                             f"{_cell(title_of(root / readme))} |")
            lines.append("")
            continue
        kinds: dict[str, list[str]] = defaultdict(list)
        for f in by_area[a]:
            kinds[kind_of(f.split("/", 2)[-1] if a != "(top)" else f[5:])].append(f)
        for k in [k for k, _ in KINDS if k in kinds] + (["Other"] if "Other" in kinds else []):
            lines += [f"### {k} ({len(kinds[k])})", "", "| File | Date | Title |", "|---|---|---|"]
            for f in sorted(kinds[k], key=lambda f: (date_of(f), f), reverse=True):
                lines.append(f"| [`{rel(f)}`]({rel(f)}) | {date_of(f)} | {_cell(title_of(root / f))} |")
            lines.append("")

    lines += ["## Elsewhere in the tree", "", "| File | Title |", "|---|---|"]
    lines += [f"| [`{f}`](../{f}) | {_cell(title_of(root / f))} |" for f in elsewhere]
    return "\n".join(lines) + "\n"


def main(argv: list[str] | None = None) -> int:
    ap = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    g = ap.add_mutually_exclusive_group(required=True)
    g.add_argument("--write", metavar="PATH")
    g.add_argument("--check", metavar="PATH")
    a = ap.parse_args(argv)
    text = build()
    if a.write:
        (ROOT / a.write).write_text(text)
        return 0
    current = (ROOT / a.check).read_text() if (ROOT / a.check).exists() else ""
    if current != text:
        print(f"{a.check} is stale: run python scripts/docs_catalog.py --write {a.check}",
              file=sys.stderr)
        return 1
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
