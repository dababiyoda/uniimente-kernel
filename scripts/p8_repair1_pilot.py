def guard(seeds) -> tuple:
    """The seeds, or PilotError: repair-1 review seeds 3000-3999 only (development seeds 0-9 in tests)."""
    seeds = tuple(seeds)
    forbidden = forbidden_seeds()
    bad = sorted((s for s in seeds if type(s) is not int or s in forbidden
                  or not (s in REVIEW_SEEDS or s in DEV_SEEDS)), key=repr)
    if bad:
        raise PilotError(f"the repair-1 pilot uses review seeds 3000-3999 only (development 0-9 in tests); "
                         f"refused {bad[:10]}")
    return seeds


