# ------------------------------------------------------------------ in-process evaluation (the cycle's own loss)
def _output(config, data) -> dict:
    """The sandbox's method (or a baseline) in a worker; an exception is no answer, as the sandbox records it."""
    try:
        if config == "no_repair":
            return {"output": D.repair_no_repair(data)}
        if config == "replanner":
            return {"output": D.repair_central_replanner(data)}
        out = D.repair_solve_with(config, data)
        return {"output": out["output"], "certificate": out["certificate"]}
    except Exception as exc:                              # noqa: BLE001
        return {"error": f"{type(exc).__name__}: {str(exc)[:160]}"}


def _job(args):
    return _output(*args)


def _baseline(config) -> bool:
    return isinstance(config, str) and config in BASELINES


def _fingerprint(item) -> str:
    """Stress items share ids with their source item but differ in data: memoise by the data's digest."""
    return E.digest(item["data"])


class Pilot:
    """Memoised per (configuration, item data), under declared resource limits."""

    def __init__(self, workers: int = WORKERS, limits: dict | None = None):
        self.target = target()
        self.outputs: dict = {}
        self.cache: dict = {}
        self.evaluations = 0                 # configuration evaluations (the limit counts these)
        self.baseline_evaluations = 0
        self.workers = workers
        self.limits = limits
        self.started = time.time()
        self._pool = None

    def close(self):
        if self._pool is not None:
            self._pool.shutdown()
            self._pool = None

    def check_limits(self):
        if self.limits and (self.evaluations > self.limits["evaluations"]
                            or time.time() - self.started > self.limits["seconds"]):
            raise LimitExceeded(f"declared limit exceeded: {self.evaluations} evaluations, "
                                f"{round(time.time() - self.started)} s, limits {self.limits}")

    def _key(self, config):
        return config if _baseline(config) else E.config_id(self.target.validate(config))

    def run(self, config, its: dict) -> dict:
        key = self._key(config)
        missing = {k: v for k, v in its.items() if (key, _fingerprint(v)) not in self.outputs}
        if missing:
            jobs = [(config, v["data"]) for v in missing.values()]
            if self.workers > 1 and len(jobs) > 4:
                if self._pool is None:
                    self._pool = ProcessPoolExecutor(self.workers)
                results = list(self._pool.map(_job, jobs, chunksize=4))
            else:
                results = [_job(j) for j in jobs]
            if _baseline(config):
                self.baseline_evaluations += len(missing)
            else:
                self.evaluations += len(missing)
            for (k, v), out in zip(missing.items(), results):
                self.outputs[(key, _fingerprint(v))] = out
        return {k: self.outputs[(key, _fingerprint(v))] for k, v in its.items()}

    def losses(self, config, its: dict) -> dict:
        key = self._key(config)
        outputs = self.run(config, its)
        todo = {k: v for k, v in its.items() if (key, _fingerprint(v)) not in self.cache}
        if todo:
            for k, loss in E.SealedEvaluator(todo, D.repair_score).losses(outputs).items():
                self.cache[(key, _fingerprint(todo[k]))] = loss
        return {k: self.cache[(key, _fingerprint(v))] for k, v in its.items()}

    def verified(self, config, its: dict) -> bool:
        return E.outputs_verified(D.repair_verify, its, self.run(config, its))


# ------------------------------------------------------------------ statistics
def clopper_pearson_upper(wrong: int, n: int, level: float = 0.95) -> float:
    """One-sided exact upper confidence bound on a binomial rate. With 0 wrong it is 1 - (1 - level)^(1/n): zero
    observed errors bound the rate; they never show it is zero."""
    from scipy.stats import beta
    return 1.0 if wrong >= n else float(beta.ppf(level, wrong + 1, n - wrong))


def errors(ls: dict) -> dict:
    wrong = sum(1 for v in ls.values() if math.isinf(v))
    return {"wrong": wrong, "n": len(ls), "rate": round(wrong / len(ls), 6),
            "upper_95": round(clopper_pearson_upper(wrong, len(ls)), 6)}


def describe(ls: dict) -> dict:
    """Mean loss as the rule reads it (infinite when any answer is wrong), wrong answers, abstentions (loss 0) and
    the mean over the remaining items (a reading aid only: the rule never drops a wrong answer)."""
    finite = [v for v in ls.values() if math.isfinite(v)]
    return {"mean_loss": round(statistics.fmean(ls.values()), 6), "wrong": len(ls) - len(finite),
            "abstain": sum(1 for v in finite if v == 0), "n": len(ls),
            "mean_loss_without_wrong": round(statistics.fmean(finite), 6) if finite else None}


def paired(a: dict, b: dict) -> dict:
    """a against b on the same items, as the cycle counts them: lower loss wins (1e-12 tolerance)."""
    wins = sum(1 for k in a if a[k] < b[k] - 1e-12)
    losses = sum(1 for k in a if b[k] < a[k] - 1e-12)
    return {"wins": wins, "losses": losses, "ties": len(a) - wins - losses,
            "sign_test_p_one_sided": round(E.sign_test(wins, losses), 6)}


def resampled(candidate: dict, incumbent: dict, n: int, *, draws: int | None = None, seed: int = 0) -> dict:
    """How often the rule's held-out step would RETAIN on ``n`` items drawn with replacement from the pool: the
    one-sided sign test gives p below each threshold and the candidate's mean loss is lower (an infinite mean, any
    wrong answer, is never lower than another infinite mean)."""
    draws = DRAWS if draws is None else draws
    keys = sorted(candidate)
    rng = random.Random(f"p8-repair1-resample:{seed}:{n}")
    counts = {name: 0 for name in THRESHOLDS}
    for _ in range(draws):
        sample = [keys[rng.randrange(len(keys))] for _ in range(n)]
        wins = sum(1 for k in sample if candidate[k] < incumbent[k] - 1e-12)
        losses = sum(1 for k in sample if incumbent[k] < candidate[k] - 1e-12)
        lower = statistics.fmean(candidate[k] for k in sample) < statistics.fmean(incumbent[k] for k in sample)
        p = E.sign_test(wins, losses)
        for name, alpha in THRESHOLDS.items():
            counts[name] += p < alpha and lower
    return {"n": n, "draws": draws, **{f"retain_rate_{name}": round(c / draws, 4) for name, c in counts.items()}}


def by_controller(pool: dict, ls: dict, reference: dict) -> dict:
    """Paired against ``reference`` within each controller subregion of the pool (reliable / unreliable)."""
    out = {}
    for region in sorted({v["category"] for v in pool.values()}):
        keys = [k for k, v in pool.items() if v["category"] == region]
        out[region] = paired({k: ls[k] for k in keys}, {k: reference[k] for k in keys})
    return out


# ------------------------------------------------------------------ the cycle's adversarial gate, as cycle() runs it
def gate(pilot, config, stress: dict) -> dict:
    """The cycle's step-5 verdict: ``evolution.stress_summary`` on item-level losses, ``evolution.stress_worsened`` on
    each kind's record and ``evolution.outputs_verified`` on the candidate's answers - the three calls
    ``evolution.cycle`` makes. No replica of the gate exists in this module."""
    inc_s, cand_s = pilot.losses(pilot.target.incumbent, stress), pilot.losses(config, stress)
    adversarial = E.stress_summary(inc_s, cand_s)
    verified = pilot.verified(config, stress)
    passes = verified and not any(E.stress_worsened(v) for v in adversarial.values())
    kinds = sorted({k.split(":")[0] for k in stress})
    return {"adversarial": adversarial, "all_outputs_verified": verified, "passes_gate": passes,
            "errors": {kind: {"incumbent": errors({k: v for k, v in inc_s.items() if k.startswith(kind + ":")}),
                              "candidate": errors({k: v for k, v in cand_s.items() if k.startswith(kind + ":")})}
                       for kind in kinds}}


def triggers(pilot, train: dict) -> dict:
    """The rule's trigger rate (incumbent worse than no repair) and, as a diagnostic outside the rule, the rate
    against the replanner."""
    inc = pilot.losses(pilot.target.incumbent, train)
    out = {}
    for name in BASELINES:
        base = pilot.losses(name, train)
        out[name] = round(sum(1 for k in train if inc[k] > base[k]) / len(train), 4)
    return {"rule_no_repair": out["no_repair"], "diagnostic_replanner": out["replanner"],
            "fires": out["no_repair"] >= E.FAILURE_RATE_TRIGGER}


def on_pool(pilot, ls: dict, reference: dict, baselines: dict, pool: dict) -> dict:
    return {**describe(ls), "errors": errors(ls), "vs_incumbent": paired(ls, reference),
            "vs_baselines": {name: paired(ls, b) for name, b in baselines.items()},
            "vs_replanner_by_controller": by_controller(pool, ls, baselines["replanner"]),
            "resampled": [resampled(ls, reference, n, seed=8) for n in RESAMPLE_SIZES]}


# ------------------------------------------------------------------ region
def region(*, pilot=None) -> dict:
    """The incumbent, the baselines and the informed fixed configurations on the pool; the trigger on every train set;
    the gate of each informed configuration on every train set's stress items."""
    started = time.time()
    guard(POOL), guard(sorted(s for seeds in TRAIN_SETS.values() for s in seeds))
    pilot = pilot or Pilot(limits=LIMITS["region"])
    pool = items(POOL)
    inc = pilot.target.incumbent
    reference = pilot.losses(inc, pool)
    baselines = {name: pilot.losses(name, pool) for name in BASELINES}
    trains = {t: items(seeds) for t, seeds in TRAIN_SETS.items()}
    stresses = {t: E._repair_stress(tr) for t, tr in trains.items()}
    out = {"schema": "greg-p8-repair1-region/1", "target": TARGET,
           "seeds": {"pool": [min(POOL), max(POOL)], "train": {t: [min(s), max(s)] for t, s in TRAIN_SETS.items()}},
           "incumbent": {"id": E.config_id(inc), "config": inc,
                         "pool": {**describe(reference), "errors": errors(reference),
                                  "vs_baselines": {n: paired(reference, b) for n, b in baselines.items()},
                                  "vs_replanner_by_controller": by_controller(pool, reference,
                                                                              baselines["replanner"])},
                         "train": {}, "stress": {}},
           "baselines": {name: {"what": BASELINES[name], **describe(b), "errors": errors(b),
                                "vs_incumbent": paired(b, reference)} for name, b in baselines.items()},
           "trigger": {}, "rows": []}
    for t, tr in trains.items():
        out["trigger"][t] = triggers(pilot, tr)
        out["incumbent"]["train"][t] = {**describe(pilot.losses(inc, tr)), "errors": errors(pilot.losses(inc, tr))}
        inc_s = pilot.losses(inc, stresses[t])
        out["incumbent"]["stress"][t] = {kind: {**describe({k: v for k, v in inc_s.items()
                                                            if k.startswith(kind + ":")}),
                                                "errors": errors({k: v for k, v in inc_s.items()
                                                                  if k.startswith(kind + ":")})}
                                         for kind in ("lossy", "late")}
        out["incumbent"]["stress"][t]["all_outputs_verified"] = pilot.verified(inc, stresses[t])
    for entry in INFORMED:
        pilot.check_limits()
        config = pilot.target.validate(entry["config"])
        ls = pilot.losses(config, pool)
        row = {"label": entry["label"], "informed_by_prior_observations": True, "id": E.config_id(config),
               "config": config, "pool": on_pool(pilot, ls, reference, baselines, pool),
               "gate": {t: gate(pilot, config, stresses[t]) for t in TRAIN_SETS}}
        passes = [row["gate"][t]["passes_gate"] for t in TRAIN_SETS]
        row["fixed_protocol_retain"] = [{"n": r["n"], **{k: round(v * sum(passes) / len(passes), 4)
                                                         for k, v in r.items() if k.startswith("retain_rate")}}
                                        for r in row["pool"]["resampled"]]
        out["rows"].append(row)
    out.update(evaluations=pilot.evaluations, baseline_evaluations=pilot.baseline_evaluations,
               seconds=round(time.time() - started, 1))
    return out


# ------------------------------------------------------------------ simulate
def simulate_one(pilot, train: dict, pool: dict, setting: dict, reference: dict, baselines: dict) -> dict:
    """One simulated cycle: the cycle's own trigger, search, train-gain gate and adversarial gate; the held-out step
    is resampled from the pool. ``resampled_retain`` follows the rule (zero unless every stage passes);
    ``diagnostic_retain_if_triggered`` drops only the trigger stage and is never part of the verdict."""
    tgt = pilot.target
    inc = tgt.incumbent
    declared = E.search_setting(tgt, setting["search"], seed=SEARCH_SEED, lhs=setting.get("lhs", 0))
    inc_train = pilot.losses(inc, train)
    inc_mean = round(statistics.fmean(inc_train.values()), 6)

    def evaluate(config):
        pilot.check_limits()
        return pilot.losses(config, train)
    found = E.run_search(tgt, evaluate, generations=GENERATIONS, population=POPULATION, seed=SEARCH_SEED,
                         incumbent_loss=inc_mean, initial=declared.get("initial", ()))
    best = found["candidate"]["config"]
    gain = E.relative_gain(inc_mean, found["candidate"]["train_mean_loss"])
    trig = triggers(pilot, train)
    stages = {"triggered": trig["fires"],
              "advances": found["candidate"]["id"] != E.config_id(inc) and gain > E.TRAIN_GAIN_MIN}
    g = gate(pilot, best, E._repair_stress(train)) if stages["advances"] else None
    stages["adversarial_passes"] = bool(g and g["passes_gate"])
    ls = pilot.losses(best, pool)
    out = {"settings": setting, "evaluated": found["evaluated"], "trigger": trig,
           "incumbent_train": {**describe(inc_train), "errors": errors(inc_train)},
           "candidate": {"id": found["candidate"]["id"], "config": best,
                         "train_mean_loss": round(found["candidate"]["train_mean_loss"], 6)},
           "train_gain": gain if math.isinf(gain) else round(gain, 4),
           "candidate_train": {**describe(pilot.losses(best, train)), "errors": errors(pilot.losses(best, train))},
           "top_train": [{"id": s["id"], "ops": s["ops"], "config": s["config"], "train_mean_loss": s["train_mean_loss"]}
                         for s in sorted(found["lineage"], key=lambda s: (s["train_mean_loss"], s["id"]))[:5]],
           "gate": g, "stages": stages, "pool": on_pool(pilot, ls, reference, baselines, pool)}
    passes = all(stages.values())
    after_trigger = stages["advances"] and stages["adversarial_passes"]
    out["resampled_retain"] = [{"n": r["n"], **{k: (v if passes else 0.0) for k, v in r.items()
                                                if k.startswith("retain_rate")}} for r in out["pool"]["resampled"]]
    out["diagnostic_retain_if_triggered"] = [{"n": r["n"], **{k: (v if after_trigger else 0.0)
                                                              for k, v in r.items() if k.startswith("retain_rate")}}
                                             for r in out["pool"]["resampled"]]
    out["would_reach_heldout"] = passes
    return out


def simulate(simulations=SIMULATIONS, *, pilot=None) -> dict:
    started = time.time()
    guard(POOL), guard(sorted(s for seeds in TRAIN_SETS.values() for s in seeds))
    pilot = pilot or Pilot(limits=LIMITS["simulate"])
    pool = items(POOL)
    reference = pilot.losses(pilot.target.incumbent, pool)
    baselines = {name: pilot.losses(name, pool) for name in BASELINES}
    runs, stopped = [], None
    for setting in simulations:
        try:
            pilot.check_limits()
            runs.append(simulate_one(pilot, items(TRAIN_SETS[setting["train"]][:setting["size"]]), pool, setting,
                                     reference, baselines))
        except LimitExceeded as exc:
            stopped = str(exc)
            break
        print(json.dumps({"done": setting, "stages": runs[-1]["stages"], "seconds": round(time.time() - started)}),
              flush=True)
    return {"schema": "greg-p8-repair1-simulate/1", "target": TARGET,
            "seeds": {"train": {k: [min(v), max(v)] for k, v in TRAIN_SETS.items()}, "pool": [min(POOL), max(POOL)]},
            "search_seed": SEARCH_SEED, "generations": GENERATIONS, "population": POPULATION,
            "complete": stopped is None and len(runs) == len(simulations), "stopped": stopped,
            "runs": runs, "evaluations": pilot.evaluations, "baseline_evaluations": pilot.baseline_evaluations,
            "seconds": round(time.time() - started, 1)}


# ------------------------------------------------------------------ the decision rule
def choose(sim: dict) -> dict:
    """The declared decision rule.

    - INCOMPLETE (a declared limit stopped the pilot) is NOT_VIABLE: an incomplete pilot never qualifies.
    - VIABLE iff the rule's trigger fires on at least 2 of the 3 train sets AND some (procedure, held-out size n) cell
      has a mean simulated P(RETAIN) at alpha 0.05, under the unchanged rule and the merged item-level gate, of at
      least 0.30.
    - The held-out size is the LARGEST n with such a cell (a smaller n is never chosen to hide rare errors); the
      procedure is the one with the highest mean P(RETAIN) at the programme-wide 0.05/7 at that n, ties to
      mutate-incumbent/1."""
    triggered = {r["settings"]["train"]: r["stages"]["triggered"] for r in sim["runs"]}
    cells = {}
    for run in sim["runs"]:
        for r in run["resampled_retain"]:
            cells.setdefault((run["settings"]["search"], r["n"]), []).append(r)
    table = [{"search": k[0], "heldout_size": k[1], "runs": len(v),
              **{f"mean_{name}": round(statistics.fmean(r[name] for r in v), 4)
                 for name in v[0] if name.startswith("retain_rate")}} for k, v in sorted(cells.items())]
    best = max((row["mean_retain_rate_alpha"] for row in table), default=0.0)
    viable_cells = [row for row in table if row["mean_retain_rate_alpha"] >= VIABLE_MIN]
    complete = sim.get("complete", True) and len(sim["runs"]) == len(SIMULATIONS)
    viable = complete and sum(triggered.values()) >= 2 and bool(viable_cells)
    choice = None
    if viable:
        n = max(row["heldout_size"] for row in viable_cells)
        at_n = sorted((row for row in viable_cells if row["heldout_size"] == n),
                      key=lambda row: (-row["mean_retain_rate_programme_7"], row["search"] != "mutate-incumbent/1"))
        choice = {"search": at_n[0]["search"], "train_size": 120, "heldout_size": n,
                  "zero_violation_upper_95_at_n": round(clopper_pearson_upper(0, n), 6)}
    return {"complete": complete, "triggered_by_train_set": triggered, "best_mean_retain_alpha": best,
            "viable_min": VIABLE_MIN, "verdict": "VIABLE" if viable else "NOT_VIABLE", "table": table,
            "choice": choice}


def diagnostic_table(sim: dict) -> list[dict]:
    """The same cells with the trigger stage dropped: design knowledge for the session owner, never the verdict."""
    cells = {}
    for run in sim["runs"]:
        for r in run["diagnostic_retain_if_triggered"]:
            cells.setdefault((run["settings"]["search"], r["n"]), []).append(r)
    return [{"search": k[0], "heldout_size": k[1], "runs": len(v), "role": "diagnostic; not the verdict",
             **{f"mean_{name}": round(statistics.fmean(r[name] for r in v), 4)
                for name in v[0] if name.startswith("retain_rate")}} for k, v in sorted(cells.items())]


def summarise(directory: Path) -> dict:
    directory = Path(directory)
    out = {}
    if (directory / "region.json").is_file():
        reg = json.loads((directory / "region.json").read_text())
        out["region"] = {"trigger": reg["trigger"], "incumbent_pool": reg["incumbent"]["pool"],
                         "baselines": reg["baselines"],
                         "informed": [{"label": r["label"], "id": r["id"], "pool_errors": r["pool"]["errors"],
                                       "vs_incumbent": r["pool"]["vs_incumbent"],
                                       "gate": {t: g["passes_gate"] for t, g in r["gate"].items()},
                                       "fixed_protocol_retain": r["fixed_protocol_retain"]} for r in reg["rows"]]}
    if (directory / "simulate.json").is_file():
        sim = json.loads((directory / "simulate.json").read_text())
        out["decision"] = choose(sim)
        out["diagnostic_without_trigger_stage"] = diagnostic_table(sim)
    return out


def main(argv=None):
    ap = argparse.ArgumentParser(description=__doc__.split("\n")[0])
    ap.add_argument("mode", choices=("region", "simulate", "summarise"))
    ap.add_argument("--dir", type=Path, help="summarise: the pilot directory")
    ap.add_argument("--out", type=Path, required=True)
    args = ap.parse_args(argv)
    if args.mode == "summarise":
        args.out.write_text(json.dumps(summarise(args.dir), indent=1) + "\n")
        print(json.dumps({"out": str(args.out)}))
        return
    if args.out.exists():
        raise SystemExit(f"refusing to overwrite {args.out}: every declared run happens exactly once")
    pilot = Pilot(limits=LIMITS.get(args.mode))
    try:
        result = {"region": region, "simulate": simulate}[args.mode](pilot=pilot)
    finally:
        pilot.close()
    args.out.parent.mkdir(parents=True, exist_ok=True)
    args.out.write_text(json.dumps(result, indent=1) + "\n")
    print(json.dumps({"out": str(args.out), "evaluations": result["evaluations"], "seconds": result["seconds"]}))


if __name__ == "__main__":
    main()
