def _problem_digest(it) -> str:
    import hashlib
    body = json.dumps({"q": it["problem"]["question"], "p": it["problem"]["payload"], "r": it.get("records")},
                      sort_keys=True)
    return hashlib.sha256(body.encode()).hexdigest()


def build() -> dict:
    suites, seen = {}, set()
    for split, per in SPLITS.items():
        items = []
        for k, stratum in enumerate(STRATA):
            rng = random.Random(SEEDS[split] + 97 * k)
            made = GENERATORS[stratum](split, rng, per * 3, f"{split[:3].upper()}-{stratum[:3].upper()}")
            kept = []
            for it in made:   # identical problems are one task, never several; no problem crosses splits
                key = _problem_digest(it)
                if key in seen:
                    continue
                seen.add(key)
                it["stratum"] = stratum
                kept.append(it)
                if len(kept) == per:
                    break
            if len(kept) < per:
                raise SystemExit(f"{split}/{stratum}: only {len(kept)} distinct problems, {per} required")
            items += kept
        suites[split] = items
    suites["adversarial"] = adversarial_items()
    for split, items in suites.items():
        (HERE / "suites").mkdir(exist_ok=True)
        (HERE / "suites" / f"crossgeo-{split}-v{VERSION}.json").write_text(
            json.dumps({"schema": "cortex-crossgeo-suite/0.2", "partition": split, "authorship_note": NOTE,
                        "strata": list(STRATA), "system_level_adversarial": SYSTEM_LEVEL, "items": items},
                       sort_keys=True, separators=(",", ":")) + "\n", encoding="utf-8")
    return {k: len(v) for k, v in suites.items()}


