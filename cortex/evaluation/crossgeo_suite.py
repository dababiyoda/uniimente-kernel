INTERVAL_RATIO = 5.0   # predeclared usefulness: a 90% interval wider than a factor of 5 is not an answer


def estimation_items(split, rng, n, sid):
    out = []
    families = ["product", "dependent", "outside_view", "dimension_error", "missing_range"]
    domains = DOMAINS[split]
    for i in range(n):
        fam = families[i % len(families)]
        iid = f"{sid}-E{i:02d}"
        target, unit, vars_ = domains[i % len(domains)]
        # jitter ranges inside the template so items differ
        variables = []
        truth = 1.0
        for name, u, lo, hi in vars_:
            f = rng.uniform(0.85, 1.2)
            lo2, hi2 = round(lo * f, 3), round(hi * f, 3)
            variables.append({"name": name, "unit": u, "low": lo2, "high": hi2})
            truth *= math.exp(rng.uniform(math.log(lo2) + .15 * math.log(hi2 / lo2),
                                          math.log(hi2) - .15 * math.log(hi2 / lo2)))
        expr = ["*", *[v["name"] for v in variables]]
        question = f"Estimate {target.replace('_', ' ')} ({unit}): " + "; ".join(
            f"{v['name']} {v['low']}-{v['high']} {v['unit']}" for v in variables) + "."
        if fam == "product":
            model = estimation(target, unit, variables, expr)
            gold = g(["recommend"], {"kind": "interval_contains", "value": truth, "max_ratio": INTERVAL_RATIO})
        elif fam == "dependent":
            a, b = variables[0]["name"], variables[1]["name"]
            rho = rng.choice([-0.6, -0.4, 0.5])
            model = estimation(target, unit, variables, expr, deps=[{"a": a, "b": b, "rho": rho,
                                                                     "reason": "stated co-movement"}])
            question += f" {a} and {b} move together (correlation {rho})."
            gold = g(["recommend"], {"kind": "interval_contains", "value": truth, "max_ratio": INTERVAL_RATIO})
        elif fam == "outside_view":
            ref_truth = truth * rng.uniform(4.0, 6.0)
            ref = {"name": "peer benchmark", "low": round(ref_truth * .7, 2), "high": round(ref_truth * 1.4, 2),
                   "unit": unit, "source": "industry survey"}
            model = estimation(target, unit, variables, expr, reference=ref)
            question += f" Peers report {ref['low']}-{ref['high']} {unit}."
            # the inside view is anchored low; the outside view is right
            gold = g(WITHHOLD + ["recommend"], {"kind": "interval_contains", "value": ref_truth,
                                                "max_ratio": INTERVAL_RATIO})
        elif fam == "dimension_error":
            extra = {"name": "overhead", "unit": "hour", "low": 10, "high": 20}
            model = estimation(target, unit, variables + [extra], ["+", expr, "overhead"])
            question += " Add 10-20 hours of overhead."
            gold = g(["abstain"], critical_if=["recommend"])
        else:
            broken = [dict(v) for v in variables]
            broken[-1].pop("high")
            model = estimation(target, unit, broken, expr)
            question += f" ({broken[-1]['name']}: upper bound unknown.)"
            gold = g(["abstain"], critical_if=["recommend"])
        out.append(item(iid, split, "standard", [fam], question, {"estimation_model": model}, gold))
    return out


