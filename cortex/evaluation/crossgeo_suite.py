# ------------------------------------------------------------------ independent oracles
def brute_linear(variables, constraints, objective=None, sense="minimize"):
    """Enumerate every integer point. variables: {name: (lo, hi)}; constraints: (coeffs, op, rhs)."""
    names = sorted(variables)
    best, best_point, any_point = None, None, None
    for values in itertools.product(*[range(variables[n][0], variables[n][1] + 1) for n in names]):
        x = dict(zip(names, values))
        ok = True
        for coeffs, op, rhs, *_ in constraints:
            lhs = sum(c * x[v] for v, c in coeffs.items())
            ok = {"<=": lhs <= rhs, ">=": lhs >= rhs, "=": lhs == rhs}[op]
            if not ok:
                break
        if not ok:
            continue
        any_point = any_point or x
        if objective is not None:
            value = sum(c * x[v] for v, c in objective.items())
            if best is None or (value < best if sense == "minimize" else value > best):
                best, best_point = value, x
    return any_point, best, best_point


def brute_schedule(jobs, shift, precedence=(), *, deadlines=None, releases=None, objective=None):
    """jobs [(name, hours)]; objective None | 'sum_start' | 'makespan'. Returns (feasible, best)."""
    names = [j for j, _ in jobs]
    dur = dict(jobs)
    deadlines, releases = deadlines or {}, releases or {}
    best = None
    feasible = False
    for starts in itertools.product(range(shift + 1), repeat=len(names)):
        s = dict(zip(names, starts))
        if any(s[j] + dur[j] > shift for j in names):
            continue
        if any(s[j] + dur[j] > deadlines[j] for j in deadlines) or any(s[j] < releases[j] for j in releases):
            continue
        if any(not (s[a] + dur[a] <= s[b] or s[b] + dur[b] <= s[a]) for a, b in itertools.combinations(names, 2)):
            continue
        if any(s[b] < s[a] + dur[a] for a, b in precedence):
            continue
        feasible = True
        if objective == "sum_start":
            v = sum(s.values())
        elif objective == "makespan":
            v = max(s[j] + dur[j] for j in names)
        else:
            return True, None
        best = v if best is None else min(best, v)
    return feasible, best


def _lin(coeffs):
    terms = [v if c == 1 else ["*", c, v] for v, c in sorted(coeffs.items())]
    return terms[0] if len(terms) == 1 else ["+", *terms]


def linear_model(requirement, variables, constraints, *, query=None, verified=True, witness=None):
    model = {"requirement": requirement,
             "variables": [{"name": n, "sort": "int", "lo": lo, "hi": hi} for n, (lo, hi) in sorted(variables.items())],
             "obligations": [], "constraints": [],
             "premises": [{"id": "P_data", "text": "the stated quantities are current", "verified": verified,
                           "evidence_ref": "planning sheet" if verified else None}],
             "witnesses": {"satisfying": [witness] if witness else [], "violating": []}}
    for i, (coeffs, op, rhs, text) in enumerate(constraints):
        model["obligations"].append({"id": f"R{i}", "text": text})
        model["constraints"].append({"id": f"C{i}", "covers": [f"R{i}"], "expr": [op, _lin(coeffs), rhs]})
    if query:
        model["query"] = query
    return model


def prose(jobs, shift, precedence=(), extra=""):
    text = f"One machine, a {shift}-hour shift, jobs: " + ", ".join(f"{j} takes {d}h" for j, d in jobs) + "."
    if precedence:
        text += " Order: " + "; ".join(f"{b} must start after {a} ends" for a, b in precedence) + "."
    return text + " One job at a time; every job finishes within the shift." + extra


def _jobs(rng, names, k, lo=1, hi=4):
    return [(n, rng.randint(lo, hi)) for n in names[:k]]


