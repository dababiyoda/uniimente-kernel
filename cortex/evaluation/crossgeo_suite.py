def formal_items(split, rng, n, sid):
    out = []
    names = NAMES[split]
    families = ["sat_schedule", "unsat_schedule", "linear_int", "entailment", "bounded_unknown"]
    for i in range(n):
        fam = families[i % len(families)]
        iid = f"{sid}-F{i:02d}"
        if fam in ("sat_schedule", "unsat_schedule"):
            k = rng.randint(2, 3)
            jobs = _jobs(rng, names, k)
            total = sum(d for _, d in jobs)
            shift = total + rng.randint(0, 2) if fam == "sat_schedule" else total - rng.randint(1, 2)
            prec = [(jobs[0][0], jobs[1][0])] if rng.random() < .5 else []
            m, _, _ = schedule(jobs, shift, prec)
            feas, _ = brute_schedule(jobs, shift, prec)
            out.append(item(iid, split, "standard", [fam], "Can every job be scheduled? " + prose(jobs, shift, prec),
                            {"formal_model": m}, g(["recommend"], {"kind": "feasible", "value": feas}, ["wrong_answer"])))
        elif fam == "linear_int":
            # integer allocation; half the cases are integrality traps (feasible over reals only)
            a, b = rng.choice([(2, 4), (3, 6), (4, 6), (2, 6)])
            trap = rng.random() < .5
            g_ = math.gcd(a, b)
            target = rng.randint(4, 12) * g_ + (rng.randint(1, g_ - 1) if trap and g_ > 1 else 0)
            hi = target
            variables = {"x": (0, hi), "y": (0, hi)}
            cons = [({"x": a, "y": b}, "=", target, f"{a}-unit crates and {b}-unit crates total exactly {target} units")]
            point, _, _ = brute_linear(variables, cons)
            m = linear_model(f"Fill exactly {target} units using whole {a}-unit and {b}-unit crates.", variables, cons,
                             witness=point)
            out.append(item(iid, split, "standard", [fam, "integrality_trap" if point is None else "integer"],
                            f"Can {target} units be filled exactly with whole {a}-unit and {b}-unit crates?",
                            {"formal_model": m},
                            g(["recommend"], {"kind": "feasible", "value": point is not None}, ["wrong_answer"])))
        elif fam == "entailment":
            jobs = _jobs(rng, names, 3, 1, 3)
            prec = [(jobs[0][0], jobs[1][0]), (jobs[1][0], jobs[2][0])]
            shift = sum(d for _, d in jobs) + rng.randint(0, 2)
            last = jobs[2][0]
            bound = jobs[0][1] + jobs[1][1] + rng.choice([0, 1])
            q = {"kind": "entailment", "property": [">=", f"s_{last}", bound]}
            m, _, _ = schedule(jobs, shift, prec, query=q)
            names_ = [j for j, _ in jobs]
            dur = dict(jobs)
            holds = all(s[2] >= bound for s in itertools.product(range(shift + 1), repeat=3)
                        if all(s[x] + dur[names_[x]] <= shift for x in range(3)) and s[1] >= s[0] + dur[names_[0]]
                        and s[2] >= s[1] + dur[names_[1]])
            out.append(item(iid, split, "standard", [fam], f"Must job {last} start at hour {bound} or later? "
                            + prose(jobs, shift, prec), {"formal_model": m},
                            g(["recommend"], {"kind": "entailed", "value": holds}, ["wrong_answer"])))
        else:   # bounded-unknown: a tight latency budget on a hard instance with a known truth
            budget = rng.choice([0.02, 0.05, 0.1])
            if rng.random() < .5:   # pigeonhole: infeasible by counting
                holes = rng.randint(8, 14)
                variables = [{"name": f"p{k}", "sort": "int", "lo": 1, "hi": holes} for k in range(holes + 1)]
                cons = [{"id": f"C{a}_{b}", "covers": ["R_distinct"], "expr": ["!=", f"p{a}", f"p{b}"]}
                        for a, b in itertools.combinations(range(holes + 1), 2)]
                m = {"requirement": f"Assign {holes + 1} crews to {holes} distinct bays, one crew per bay.",
                     "variables": variables, "obligations": [{"id": "R_distinct", "text": "no two crews share a bay"}],
                     "constraints": cons, "premises": [{"id": "P", "text": "bay count is current", "verified": True}]}
                q, truth = f"Can {holes + 1} crews each get their own bay out of {holes}?", False
            else:                   # planted 3-colouring near the hardness threshold: feasible by construction
                nodes = rng.randint(30, 60)
                colour = [rng.randrange(3) for _ in range(nodes)]
                edges = sorted({(a, b) for a in range(nodes) for b in range(a + 1, nodes)
                                if colour[a] != colour[b] and rng.random() < 4.6 / (nodes * 2 / 3)})
                m = {"requirement": f"Give each of {nodes} meetings one of 3 slots; linked meetings differ.",
                     "variables": [{"name": f"c{k}", "sort": "int", "lo": 0, "hi": 2} for k in range(nodes)],
                     "obligations": [{"id": "R_link", "text": "linked meetings take different slots"}],
                     "constraints": [{"id": f"E{a}_{b}", "covers": ["R_link"], "expr": ["!=", f"c{a}", f"c{b}"]}
                                     for a, b in edges],
                     "premises": [{"id": "P", "text": "the link list is complete", "verified": True}]}
                q, truth = f"Can {nodes} meetings with {len(edges)} conflicts fit into 3 slots?", True
            out.append(item(iid, split, "standard", [fam], f"{q} Answer within {int(budget * 1000)} ms.",
                            {"formal_model": m, "resources": {"max_latency_s": budget}},
                            g(["recommend", "abstain"], {"kind": "feasible", "value": truth}, ["wrong_answer"]),
                            notes="truth known by construction; a solver may not decide it inside the budget"))
    return out


