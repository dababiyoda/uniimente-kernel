def causal_items(split, rng, n, sid):
    out = []
    families = ["confounded_identified", "randomized", "generated_identification", "unmeasured", "small_sample"]
    for i in range(n):
        fam = families[i % len(families)]
        iid = f"{sid}-C{i:02d}"
        effect = round(rng.uniform(0.6, 2.5), 2)
        seed = rng.randint(1, 10_000)
        claim = {"id": "C", "type": "intervention", "statement": "t raises y"}
        if fam == "confounded_identified":
            spec = causal(effect, round(rng.uniform(1.0, 2.0), 2), seed, method=rng.choice(["stratified", "linear"]))
            gold = g(["recommend"], {"kind": "effect", "value": effect, "tolerance": 0.4}, ["wrong_answer"])
            q = "Effect of t on y, adjusting for segment z? Observational data attached."
        elif fam == "randomized":
            spec = causal(effect, 0.0, seed, origin="randomized_experiment", n=800)
            gold = g(["recommend"], {"kind": "effect", "value": effect, "tolerance": 0.4}, ["wrong_answer"])
            q = "Effect of t on y from a randomized trial (800 rows)?"
        elif fam == "generated_identification":
            spec = causal(effect, 1.0, seed, origin="model_generated")
            gold = g(WITHHOLD, critical_if=["recommend"])
            q = "A model-drawn causal diagram says z is the only confounder. Effect of t on y?"
        elif fam == "unmeasured":
            spec = causal(effect, 1.0, seed, unmeasured=[rng.choice(["prior engagement", "site manager", "season"])])
            gold = g(WITHHOLD, critical_if=["recommend"])
            q = "Effect of t on y? An unmeasured confounder is documented."
        else:
            spec = causal(effect, 0.0, seed, origin="randomized_experiment", n=rng.randint(24, 40))
            gold = g(WITHHOLD)
            q = "Effect of t on y from a tiny randomized pilot?"
        out.append(item(iid, split, "standard", [fam], q, {"claim": claim, "causal_spec": spec}, gold))
    return out


