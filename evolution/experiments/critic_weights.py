"""Parameterized content-quality scorer: the fast loop's experiment target.

The organ's critic (DALEOBANKS services/critic.py, git blob
b11e8b313241120cf6ca286cf715eb2e309dc814) scores drafts by additive
keyword signals with no penalty side: hype, vagueness, and unrealistic
claims pass unpenalized. This module re-expresses that scorer as a
weight configuration over a feature set, so the EvolutionLoop can
compete configurations against each other on a doctrine-labeled corpus.

BASELINE_WEIGHTS reproduces the organ critic exactly: the nine additive
signals with the organ's own weights, penalty weights at zero. Parity
against the real critic on every corpus text is asserted by the harness
reference artifact (critic_baseline_reference.json), generated by the
organ module itself, not by a paraphrase.

Penalty features are count-based (each marker hit applies the weight).
The additive signals are presence-based, exactly as in the organ.
Scores clamp to [0, 100]: the organ clamps at 100, and a scorer that
drives text below zero is measuring nothing.
"""

import json
import re
from pathlib import Path

CORPUS_PATH = Path(__file__).resolve().parent / "critic_corpus.json"
REFERENCE_PATH = Path(__file__).resolve().parent / "critic_baseline_reference.json"

# Presence-based additive signals, regexes identical to the organ critic.
ADDITIVE_SIGNALS = {
    "specific_numbers": r"\b\d+\s*(?:days?|weeks?|months?|%|dollars?|\$)",
    "concrete_actions": r"\b(?:implement|deploy|create|build|establish|launch|start)\b",
    "measurable_outcomes": r"(?:>\s*\d+%|\b(?:increase|decrease|improve|reduce|achieve|reach)\s+(?:by\s+)?\d+)",
    "time_bounds": r"\b(?:within|in|by)\s+\d+\s*(?:days?|weeks?|months?)",
    "stakeholder_mentions": r"\b(?:users?|customers?|teams?|organizations?|communities?)\b",
}

# Count-based penalty markers, derived from the writing doctrine's
# residue lists (hype, vagueness, unrealistic claims).
PENALTY_MARKERS = {
    "hype_penalty": [
        "revolutionary", "game-changing", "game changer", "cutting-edge",
        "next-level", "seamless", "world-class", "synergy", "disruptive",
    ],
    "vague_penalty": [
        "might help", "could work", "maybe", "perhaps", "somehow",
        "something", "stuff", "things",
    ],
    "unrealistic_penalty": [
        "100% success", "100% guarantee", "no risk", "perfect solution",
        "solve everything", "fix all",
    ],
}

BASELINE_WEIGHTS = {
    "length_high": 15.0,
    "length_mid": 10.0,
    "length_low": 5.0,
    "specific_numbers": 20.0,
    "concrete_actions": 15.0,
    "measurable_outcomes": 20.0,
    "time_bounds": 15.0,
    "stakeholder_mentions": 10.0,
    "question_mark": 5.0,
    "kpi_ref": 10.0,
    "risk_ref": 5.0,
    "hype_penalty": 0.0,
    "vague_penalty": 0.0,
    "unrealistic_penalty": 0.0,
}

WEIGHT_KEYS = tuple(BASELINE_WEIGHTS.keys())


def score_text(text, weights):
    """Score one text under a weight configuration. Mirrors the organ's
    scoring path exactly when given BASELINE_WEIGHTS."""
    merged = dict(BASELINE_WEIGHTS)
    merged.update({k: float(v) for k, v in weights.items() if k in merged})
    lowered = text.lower()
    if len(text) > 100:
        score = merged["length_high"]
    elif len(text) > 50:
        score = merged["length_mid"]
    else:
        score = merged["length_low"]
    for name, pattern in ADDITIVE_SIGNALS.items():
        if re.search(pattern, lowered):
            score += merged[name]
    if "?" in text:
        score += merged["question_mark"]
    if "kpi" in lowered or "kpis" in lowered:
        score += merged["kpi_ref"]
    if "risk" in lowered or "risks" in lowered:
        score += merged["risk_ref"]
    for name, markers in PENALTY_MARKERS.items():
        hits = sum(
            len(re.findall(r"\b" + re.escape(marker) + r"\b", lowered))
            for marker in markers
        )
        score += merged[name] * hits
    return max(0.0, min(100.0, score))


def load_corpus():
    with open(CORPUS_PATH, "r", encoding="utf-8") as handle:
        return json.load(handle)


def score_corpus(weights=None):
    """Score every corpus text. Returns {text_id: score}."""
    corpus = load_corpus()
    weights = weights or {}
    return {
        item["id"]: score_text(item["text"], weights)
        for item in corpus["texts"]
    }


def measure_config(weights=None):
    """The isolated-loop entry point: separation metrics for one config.

    separation_margin: min score over doctrine-good texts minus max score
        over doctrine-bad texts. Positive means the worst good text still
        outranks the best bad text.
    false_accepts: count of doctrine-bad texts at or above the corpus
        accept threshold.
    good_floor: min score over doctrine-good texts. Guards against
        configurations that separate by destroying signal: a branch that
        flattens every text to near-zero separates fine and accepts no
        bad text, and still loses on this metric.
    """
    corpus = load_corpus()
    threshold = float(corpus["accept_threshold"])
    scores = score_corpus(weights or {})
    good = [scores[i["id"]] for i in corpus["texts"] if i["label"] == "good"]
    bad = [scores[i["id"]] for i in corpus["texts"] if i["label"] == "bad"]
    return {
        "separation_margin": float(min(good) - max(bad)),
        "false_accepts": float(sum(1 for s in bad if s >= threshold)),
        "good_floor": float(min(good)),
    }


def baseline_parity_errors():
    """Texts where BASELINE_WEIGHTS diverges from the organ reference.

    The reference is produced by the real organ critic in the harness.
    Any divergence here means the experiment's baseline is not the
    organ's actual scorer and the cycle must not run.
    """
    if not REFERENCE_PATH.exists():
        return ["reference artifact missing: critic_baseline_reference.json"]
    with open(REFERENCE_PATH, "r", encoding="utf-8") as handle:
        reference = json.load(handle)["scores"]
    ours = score_corpus({})
    return [
        f"{text_id}: reference {reference[text_id]} != ours {ours[text_id]}"
        for text_id in reference
        if abs(reference[text_id] - ours.get(text_id, float("nan"))) > 1e-9
    ]
