def optimization_items(split, rng, n, sid):
    out = []
    names = NAMES[split]
    families = ["schedule_optimum", "schedule_infeasible", "linear_optimum", "schedule_words"]
    for i in range(n):
        fam = families[i % len(families)]
        iid = f"{sid}-O{i:02d}"
        if fam == "schedule_optimum":
            jobs = _jobs(rng, names, 3)
            shift = sum(d for _, d in jobs) + rng.randint(1, 3)
            prec = [(jobs[1][0], jobs[0][0])] if rng.random() < .5 else []
            objective = rng.choice(["sum_start", "makespan"])
            if objective == "sum_start":
                q = {"kind": "optimize", "sense": "minimize", "objective": ["+", *[f"s_{j}" for j, _ in jobs]]}
            else:
                q = {"kind": "optimize", "sense": "minimize", "objective": "s_end"}
            m, _, _ = schedule(jobs, shift, prec, query=q)
            if objective == "makespan":
                m["variables"].append({"name": "s_end", "sort": "int", "lo": 0, "hi": shift})
                m["obligations"].append({"id": "R_ms", "text": "s_end is the latest completion"})
                m["constraints"] += [{"id": f"C_ms_{j}", "covers": ["R_ms"], "expr": [">=", "s_end", ["+", f"s_{j}", d]]}
                                     for j, d in jobs]
                m["witnesses"] = {"satisfying": [], "violating": []}
            _, best = brute_schedule(jobs, shift, prec, objective=objective)
            what = "the sum of start times" if objective == "sum_start" else "the time the last job ends"
            out.append(item(iid, split, "standard", [fam, objective], f"Minimise {what}. " + prose(jobs, shift, prec),
                            {"formal_model": m},
                            g(["recommend"], {"kind": "objective", "value": best}, ["wrong_answer"])))
        elif fam == "schedule_infeasible":
            jobs = _jobs(rng, names, 3, 2, 4)
            shift = sum(d for _, d in jobs) + 2
            dl_job = jobs[2][0]
            prec = [(jobs[0][0], dl_job), (jobs[1][0], dl_job)]
            deadline = jobs[0][1] + jobs[1][1] + jobs[2][1] - rng.randint(1, 2)
            q = {"kind": "optimize", "sense": "minimize", "objective": ["+", *[f"s_{j}" for j, _ in jobs]]}
            m, _, _ = schedule(jobs, shift, prec, query=q, witnesses=False)
            m["obligations"].append({"id": "R_dl", "text": f"job {dl_job} finishes by hour {deadline}"})
            m["constraints"].append({"id": "C_dl", "covers": ["R_dl"],
                                     "expr": ["<=", ["+", f"s_{dl_job}", jobs[2][1]], deadline]})
            m["requirement"] += f" Job {dl_job} must finish by hour {deadline}."
            feas, best = brute_schedule(jobs, shift, prec, deadlines={dl_job: deadline}, objective="sum_start")
            gold = (g(["recommend"], {"kind": "objective", "value": best}, ["wrong_answer"]) if feas else
                    g(["recommend"], {"kind": "feasible", "value": False}, ["wrong_answer"]))
            out.append(item(iid, split, "standard", [fam], f"Minimise the sum of start times; job {dl_job} must "
                            f"finish by hour {deadline}. " + prose(jobs, shift, prec), {"formal_model": m}, gold))
        elif fam == "linear_optimum":
            demand = rng.randint(7, 15)
            c1, c2 = rng.choice([(30, 45), (20, 35), (25, 40), (18, 30)])
            cap_a, cap_b = rng.randint(4, 8), rng.randint(3, 7)
            variables = {"a": (0, cap_a), "b": (0, cap_b)}
            cons = [({"a": 1, "b": 2}, ">=", demand, f"juniors cover 1 unit, seniors 2; at least {demand} units")]
            point, best, best_point = brute_linear(variables, cons, objective={"a": c1, "b": c2})
            q = {"kind": "optimize", "sense": "minimize", "objective": _lin({"a": c1, "b": c2})}
            m = linear_model(f"Cover at least {demand} units with juniors (1 unit, {c1} USD, at most {cap_a}) and "
                             f"seniors (2 units, {c2} USD, at most {cap_b}); minimise cost.", variables, cons,
                             query=q, witness=point)
            gold = (g(["recommend"], {"kind": "objective", "value": best}, ["wrong_answer"]) if point else
                    g(["recommend"], {"kind": "feasible", "value": False}, ["wrong_answer"]))
            out.append(item(iid, split, "standard", [fam], f"Cheapest staffing covering {demand} units? Juniors cost "
                            f"{c1} USD (1 unit, at most {cap_a}); seniors cost {c2} USD (2 units, at most {cap_b}).",
                            {"formal_model": m}, gold))
        else:   # schedule_words: the seed composition
            jobs = _jobs(rng, names, rng.randint(2, 3))
            shift = sum(d for _, d in jobs) + rng.randint(0, 3)
            lines = [f"Shift: {shift} hours."] + [f"Job {j} takes {d} hours." for j, d in jobs]
            prec = []
            if rng.random() < .6:
                prec = [(jobs[0][0], jobs[1][0])]
                lines.append(f"{jobs[0][0]} before {jobs[1][0]}.")
            lines += ["One machine; one job at a time.", "Minimize the makespan."]
            feas, best = brute_schedule(jobs, shift, prec, objective="makespan")
            gold = (g(["recommend"], {"kind": "objective", "value": best}, ["wrong_answer"]) if feas else
                    g(["recommend"], {"kind": "feasible", "value": False}, ["wrong_answer"]))
            out.append(item(iid, split, "standard", [fam], "Schedule these jobs as written.",
                            {"schedule_request": {"text": " ".join(lines),
                                                  "availability_evidence": "shift roster"}}, gold))
    return out


